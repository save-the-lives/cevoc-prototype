import React from 'react';
import { Link, Button, Alert, Breadcrumbs, StatusTag, ErrorState, Loading } from '../components/ui.jsx';
import { useApp, apiCtx } from '../state.js';
import { api, can } from '../services/mockApi.js';
import { useAsync } from '../useAsync.js';
import { SITES } from '../data/mockData.js';
import { fmtDate, TODAY } from '../format.js';

function downloadCertificate(c, site) {
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${c.id}</title>
<style>body{font-family:Arial,sans-serif;max-width:720px;margin:40px auto;color:#22272b}h1{color:#002664}td{padding:6px 12px;border-bottom:1px solid #ddd}.s{color:#b81237;font-weight:bold}</style></head><body>
<p class="s">SAMPLE – MOCK DATA – NOT A REAL CERTIFICATE</p><h1>${c.type}</h1><table>
<tr><td>Certificate</td><td>${c.id}</td></tr><tr><td>Camera</td><td>${site.code} – ${site.name}</td></tr>
<tr><td>Tested on</td><td>${fmtDate(c.testedOn)}</td></tr><tr><td>In force</td><td>${fmtDate(c.validFrom)} to ${fmtDate(c.validTo)}</td></tr>
</table><p>Generated by the CEVOC prototype on ${fmtDate(TODAY)}.</p></body></html>`;
  const url = URL.createObjectURL(new Blob([html], { type: 'text/html' }));
  const a = Object.assign(document.createElement('a'), { href: url, download: `${c.id}-SAMPLE.html` });
  a.click();
  URL.revokeObjectURL(url);
}

export default function Certificate({ id }) {
  const app = useApp();
  const cert = useAsync(() => api.getCertificate(apiCtx(app), id), [id, app.demo.outage, app.overrides]);
  const officerView = can(app.officer, 'cert:restricted');
  const canWithdraw = can(app.officer, 'content:withdraw');

  if (cert.error) return <div className="nsw-container cevoc-page"><h1>Certificate {id}</h1><ErrorState error={cert.error} onRetry={cert.reload} /></div>;
  if (cert.loading) return <div className="nsw-container cevoc-page"><Loading text="Loading certificate" /></div>;

  const c = cert.data;
  const hidden = !c || (c.status === 'restricted' && !officerView);
  if (hidden)
    return (
      <div className="nsw-container cevoc-page">
        <h1>Certificate not found</h1>
        <p>This certificate doesn't exist or isn't available publicly. <Link to="/cameras">Search cameras</Link></p>
      </div>
    );

  const site = SITES.find((s) => s.code === c.site);
  const withdrawn = c.status === 'withdrawn';
  const live = c.status === 'published' && c.validFrom <= TODAY && c.validTo >= TODAY;

  const toggle = () => {
    const next = withdrawn ? 'published' : 'withdrawn';
    app.setOverride(c.id, next, withdrawn ? 'Restored to public view' : 'Withdrawn from public view');
  };

  return (
    <div className="nsw-container cevoc-page">
      <Breadcrumbs items={[['Home', '/'], ['Cameras and certificates', '/cameras'], [site.name, `/cameras/${site.code}`], [c.id, `/certificates/${c.id}`]]} />
      <h1 className="no-print">Certificate {c.id}</h1>

      {withdrawn && (
        <Alert type="warning" title="This certificate has been withdrawn">
          <p>{c.withdrawnReason || 'It is no longer available through this service.'}</p>
        </Alert>
      )}

      {(!withdrawn || officerView) && (
        <article className="cevoc-certificate">
          <p className="cevoc-certificate__sample">SAMPLE · MOCK DATA · NOT A REAL CERTIFICATE</p>
          <h2>{c.type}</h2>
          <p><StatusTag status={withdrawn ? 'withdrawn' : c.status === 'restricted' ? 'restricted' : live ? 'current' : 'expired'} /></p>
          <table className="nsw-table">
            <tbody>
              <tr><th scope="row">Certificate number</th><td>{c.id}</td></tr>
              <tr><th scope="row">Camera</th><td>{site.code} · {site.type}</td></tr>
              <tr><th scope="row">Location</th><td>{site.name} ({site.direction})</td></tr>
              <tr><th scope="row">Tested on</th><td>{fmtDate(c.testedOn)}</td></tr>
              <tr><th scope="row">In force</th><td>{fmtDate(c.validFrom)} to {fmtDate(c.validTo)}</td></tr>
            </tbody>
          </table>

          {officerView ? (
            <>
              <h3>Restricted technical details <StatusTag status="restricted" /></h3>
              <table className="nsw-table">
                <tbody>
                  <tr><th scope="row">Device serial</th><td>{c.restricted.deviceSerial}</td></tr>
                  <tr><th scope="row">Match value</th><td>{c.restricted.matchValue}</td></tr>
                  <tr><th scope="row">Tested by</th><td>{c.restricted.testedBy}</td></tr>
                  <tr><th scope="row">Speed accuracy</th><td>{c.restricted.speedAccuracy}</td></tr>
                  <tr><th scope="row">Image capture</th><td>{c.restricted.imageCapture}</td></tr>
                  <tr><th scope="row">Time source</th><td>{c.restricted.timeSource}</td></tr>
                </tbody>
              </table>
            </>
          ) : (
            <p className="cevoc-muted no-print">Additional technical details are available to authorised officers.</p>
          )}
        </article>
      )}

      {!withdrawn && (
        <div className="cevoc-actions no-print">
          <Button onClick={() => window.print()}>Print certificate</Button>
          <Button variant="dark-outline" onClick={() => downloadCertificate(c, site)}>Download certificate</Button>
        </div>
      )}

      {canWithdraw && c.status !== 'restricted' && (
        <section className="cevoc-panel cevoc-panel--officer no-print">
          <h2 className="cevoc-h2">Publication control</h2>
          <p>Withdrawing hides this certificate from public view. The source record is not changed and the action is logged.</p>
          <Button variant={withdrawn ? 'dark' : 'danger'} onClick={toggle}>{withdrawn ? 'Restore to public view' : 'Withdraw from public view'}</Button>
        </section>
      )}
    </div>
  );
}
