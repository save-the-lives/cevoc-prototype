package cevoc.adapter.out.demo;

import cevoc.application.port.in.LookupSink;
import cevoc.application.port.out.DemoCatalogPort;
import cevoc.application.service.LookupPenaltyService;
import cevoc.domain.CertificateItem;
import cevoc.domain.EvidenceItem;
import cevoc.domain.LookupTrace;
import cevoc.domain.PenaltyLookupRequest;
import cevoc.domain.PenaltyLookupResult;
import cevoc.domain.RegistrationScope;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Generates the two files that are derived from the factory's scenario list, so neither can go stale:
 * the table in docs/DEMO-DATA.md (between the GENERATED markers) and scripts/visual-check-demo-cases.json (the hub list, the
 * stream events of every case and the sample images, for the offline visual check). {@code DemoArtifactsTest} fails when
 * either file differs. To refresh them run {@code mvn -q test -Dtest=DemoArtifactsTest -Dcevoc.demo.regenerate=true}
 * (or {@link #main}).
 */
public final class DemoArtifacts {

    static final String BEGIN = "<!-- BEGIN GENERATED: scenario table (DemoArtifacts, do not edit by hand) -->";
    static final String END = "<!-- END GENERATED -->";
    static final String WRONG_PLATE = "WRONG1";

    private static final ObjectMapper MAPPER = new ObjectMapper().registerModule(new JavaTimeModule())
            .disable(SerializationFeature.WRITE_DATES_AS_TIMESTAMPS)
            .enable(SerializationFeature.ORDER_MAP_ENTRIES_BY_KEYS).enable(SerializationFeature.INDENT_OUTPUT);

    private DemoArtifacts() {}

    // ---------------------------------------------------------------- markdown

    static String markdownTable(DemoCaseFactory factory) {
        DemoCatalog catalog = new DemoCatalog(factory);
        StringBuilder b = new StringBuilder();
        b.append(BEGIN).append('\n');
        for (DemoCatalogPort.Program p : catalog.programs()) {
            b.append("\n### ").append(p.prefix()).append(' ').append(p.label()).append(p.built() ? "" : " (not built yet)").append("\n\n");
            if (!p.built()) {
                b.append(p.note()).append(" The prefix is reserved: the sequence ranges below apply when it is built.\n");
                continue;
            }
            b.append("| Number | Kind | What it shows | Images | Certificates | Video | Program details |\n|---|---|---|---|---|---|---|\n");
            for (DemoCatalogPort.Group g : p.groups()) {
                for (DemoCatalogPort.Case c : g.cases()) {
                    b.append("| `").append(c.number()).append("` | ").append(g.title()).append(" | **").append(cell(c.title())).append(".** ")
                            .append(cell(c.description())).append(" | ")
                            .append(c.transparencyText().get("images")).append(" | ").append(c.transparencyText().get("certificates"))
                            .append(" | ").append(c.transparencyText().get("video")).append(" | ").append(c.transparencyText().get("details"))
                            .append(" |\n");
                }
            }
        }
        return b.append('\n').append(END).toString();
    }

    private static String cell(String s) {
        return s.replace("|", "/");
    }

    // ---------------------------------------------------------------- fixture json

    static String fixtureJson(DemoCaseFactory factory) throws IOException {
        DemoCatalog catalog = new DemoCatalog(factory);
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("_comment", "GENERATED by DemoArtifacts from the demo scenario list. Do not edit by hand. Fictitious data only.");
        root.put("catalog", Map.of("notice", "Demo data, not real notices. Every number, place and image here is fictitious.",
                "programs", catalog.programs()));
        Map<String, Object> cases = new TreeMap<>();
        for (DemoScenario s : factory.scenarios()) {
            Map<String, Object> one = new LinkedHashMap<>();
            one.put("offenceDate", s.offenceDate().toString());
            one.put("events", events(factory, s, null));
            if (s.plate() != DemoScenario.Plate.NONE) {
                one.put("eventsWithPlate", events(factory, s, s.plate() == DemoScenario.Plate.GATED ? DemoCaseFactory.PLATE : WRONG_PLATE));
            }
            Map<String, String> media = new TreeMap<>();
            for (DemoMediaSet.Item i : factory.mediaSet(s).items()) {
                if (i.key().startsWith("demo/")) {
                    String name = i.key().substring(i.key().lastIndexOf('/') + 1);
                    media.put(name, new String(factory.mediaSource().read(s.number(), name).orElseThrow().data(), StandardCharsets.UTF_8));
                }
            }
            one.put("media", media);
            cases.put(s.number(), one);
        }
        root.put("cases", cases);
        return MAPPER.writeValueAsString(root) + "\n";
    }

    /** The stream events of one lookup, shaped like PenaltyLookupStreamController sends them. */
    static List<List<Object>> events(DemoCaseFactory factory, DemoScenario s, String plate) {
        List<List<Object>> out = new ArrayList<>();
        LookupSink sink = recordingSink(out);
        var port = new DemoPenaltyLookupAdapter(factory);
        var service = new LookupPenaltyService(port, DemoSignedLinks.wrapping((k, v) -> {
            throw new IllegalStateException("not a demo key");
        }), null, null);
        PenaltyLookupRequest request = new PenaltyLookupRequest(s.number(), LocalDate.of(2026, 11, 5));
        LookupTrace.begin(false);
        try {
            if (plate == null) {
                service.lookup(request, sink);
            } else {
                RegistrationScope.with(plate, () -> {
                    service.lookup(request, sink);
                    return null;
                });
            }
        } finally {
            LookupTrace.end();
        }
        return out;
    }

    static LookupSink recordingSink(List<List<Object>> out) {
        return new LookupSink() {
            @Override
            public void details(PenaltyLookupResult d) {
                Map<String, Object> m = new LinkedHashMap<>();
                m.put("status", d.status());
                m.put("infringementNumber", d.infringementNumber());
                m.put("summary", d.summary());
                m.put("notice", d.notice());
                m.put("source", d.source());
                out.add(List.of("details", m));
                if (d.status() != PenaltyLookupResult.Status.FOUND) {
                    out.add(List.of("evidence", Map.of("evidence", List.of(), "plateRequired", false)));
                    out.add(List.of("certificates", Map.of("certificates", List.of())));
                }
            }

            @Override
            public void evidence(List<EvidenceItem> evidence, boolean plateRequired) {
                out.add(List.of("evidence", Map.of("evidence", evidence, "plateRequired", plateRequired)));
            }

            @Override
            public void extra(Map<String, Object> details) {
                out.add(List.of("extra", Map.of("details", details)));
            }

            @Override
            public void certificates(List<CertificateItem> certificates) {
                out.add(List.of("certificates", Map.of("certificates", certificates)));
            }

            @Override
            public void done() {
                out.add(List.of("done", Map.of("ok", true)));
            }

            @Override
            public void error(String cause) {
                out.add(List.of("error", Map.of("cause", cause)));
            }
        };
    }

    // ---------------------------------------------------------------- files

    /** Replaces the generated region of a document (the markers must exist). */
    static String withTable(String doc, String table) {
        int a = doc.indexOf(BEGIN);
        int z = doc.indexOf(END);
        if (a < 0 || z < a) {
            throw new IllegalStateException("generated markers missing");
        }
        return doc.substring(0, a) + table + doc.substring(z + END.length());
    }

    /** Writes both files under the repository root (the directory that holds docs/ and scripts/). */
    public static void main(String[] args) throws IOException {
        Path root = Path.of(args.length > 0 ? args[0] : "..");
        write(root);
    }

    static void write(Path root) throws IOException {
        DemoCaseFactory factory = new DemoCaseFactory(new SampleMediaSource());
        Path doc = root.resolve("docs/DEMO-DATA.md");
        Files.writeString(doc, withTable(Files.readString(doc), markdownTable(factory)));
        Files.writeString(root.resolve("scripts/visual-check-demo-cases.json"), fixtureJson(factory));
    }
}
