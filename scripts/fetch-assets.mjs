#!/usr/bin/env node
// Downloads sample images/videos from a reference prototype site into public/assets/fetched,
// then rebuilds public/assets/manifest.json from public/assets/fetched + public/assets/media.
//
//   npm run assets:fetch                      # default site below
//   npm run assets:fetch -- https://other.site/
//   npm run assets:scan                       # no download; just rebuild manifest (e.g. after adding videos)
//
// Needs Node 18+ (built-in fetch). Only use with sites you're permitted to copy sample assets from.

import { mkdir, writeFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';

const DEFAULT_SITE = 'https://faes-core-operations.lukeakelly.chatgpt.site/';
const args = process.argv.slice(2);
const scanOnly = args.includes('--scan-only');
const SITE = args.find((a) => a.startsWith('http')) || DEFAULT_SITE;

const ASSETS = path.resolve('public/assets');
const FETCHED = path.join(ASSETS, 'fetched');
const MEDIA = path.join(ASSETS, 'media');
const IMG_EXT = /\.(png|jpe?g|webp|gif|avif|svg)$/i;
const VID_EXT = /\.(mp4|webm|mov|m4v)$/i;
const SKIP = /(favicon|apple-touch|icon[-_.]|logo|sprite|manifest)/i;
const MIN_BYTES = 4 * 1024; // ignore tiny UI icons

const abs = (u, base) => {
  try { return new URL(u, base).href; } catch { return null; }
};

function collect(text, base, found) {
  const add = (u) => {
    if (!u || u.startsWith('data:') || u.startsWith('blob:')) return;
    const a = abs(u.trim(), base);
    if (!a) return;
    const p = new URL(a).pathname;
    if ((IMG_EXT.test(p) || VID_EXT.test(p)) && !SKIP.test(p)) found.add(a);
  };
  for (const m of text.matchAll(/(?:src|href|poster|data-src)\s*=\s*["']([^"']+)["']/gi)) add(m[1]);
  for (const m of text.matchAll(/srcset\s*=\s*["']([^"']+)["']/gi)) m[1].split(',').forEach((s) => add(s.trim().split(/\s+/)[0]));
  for (const m of text.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/gi)) add(m[1]);
  for (const m of text.matchAll(/["'`]((?:https?:\/\/|\.{0,2}\/)?[\w\-./%@]+\.(?:png|jpe?g|webp|gif|avif|svg|mp4|webm))["'`]/gi)) add(m[1]);
}

async function get(url) {
  const r = await fetch(url, { headers: { 'User-Agent': 'cevoc-prototype-asset-fetch' } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r;
}

async function download() {
  console.log(`Fetching ${SITE}`);
  const html = await (await get(SITE)).text();
  const found = new Set();
  collect(html, SITE, found);

  // Follow same-origin JS/CSS bundles (SPA sites reference images inside them).
  const bundles = new Set();
  for (const m of html.matchAll(/(?:src|href)\s*=\s*["']([^"']+\.(?:js|mjs|css)(?:\?[^"']*)?)["']/gi)) {
    const u = abs(m[1], SITE);
    if (u && new URL(u).origin === new URL(SITE).origin) bundles.add(u);
  }
  for (const b of bundles) {
    try {
      const text = await (await get(b)).text();
      collect(text, b.endsWith('.css') ? b : SITE, found);
      for (const m of text.matchAll(/["'`](\.?\/?assets\/[\w\-.]+\.(?:js|css))["'`]/gi)) {
        const u = abs(m[1], SITE);
        if (u && !bundles.has(u)) bundles.add(u); // lazy chunks
      }
    } catch (e) {
      console.warn(`  skip bundle: ${e.message}`);
    }
  }

  console.log(`Found ${found.size} candidate asset(s)`);
  await mkdir(FETCHED, { recursive: true });
  let n = 0;
  for (const url of found) {
    try {
      const r = await get(url);
      const buf = Buffer.from(await r.arrayBuffer());
      if (buf.length < MIN_BYTES) continue;
      const base = path.basename(new URL(url).pathname).replace(/[^\w.\-]/g, '_');
      const name = `${String(++n).padStart(2, '0')}-${base}`;
      await writeFile(path.join(FETCHED, name), buf);
      console.log(`  saved fetched/${name} (${Math.round(buf.length / 1024)} KB)`);
    } catch (e) {
      console.warn(`  skip ${url}: ${e.message}`);
    }
  }
  if (!n) console.warn('No usable images downloaded. The prototype will keep using built-in placeholders.');
}

async function list(dir, rel, re) {
  try {
    const files = (await readdir(dir)).filter((f) => re.test(f)).sort();
    const out = [];
    for (const f of files) if ((await stat(path.join(dir, f))).isFile()) out.push({ file: `${rel}/${f}` });
    return out;
  } catch {
    return [];
  }
}

async function writeManifest() {
  const images = [...(await list(FETCHED, 'fetched', IMG_EXT)), ...(await list(MEDIA, 'media', IMG_EXT))];
  const videos = [...(await list(FETCHED, 'fetched', VID_EXT)), ...(await list(MEDIA, 'media', VID_EXT))];
  const manifest = {
    note: 'Generated by scripts/fetch-assets.mjs. Image order maps to `slot` numbers in src/data/mockData.js (0-2 offence, 3-5 camera sites). Reorder entries to change which image appears where.',
    generated: new Date().toISOString(),
    source: scanOnly ? 'local scan' : SITE,
    images,
    videos,
  };
  await writeFile(path.join(ASSETS, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  console.log(`manifest.json: ${images.length} image(s), ${videos.length} video(s)`);
}

if (!scanOnly) {
  try {
    await download();
  } catch (e) {
    console.error(`Download failed: ${e.message}`);
  }
}
await writeManifest();
